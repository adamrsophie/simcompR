lag_subsystem <- function() {
  lag <- sim_subsystem("lag", params = list(tau = 1, gain = 1))
  sim_add_block(lag, "inport", "u", index = 1)
  sim_add_block(lag, "gain", "k", gain = sim_param("gain"))
  sim_add_block(lag, "subtract", "e")
  sim_add_block(lag, "gain", "inv", gain = sim_param("rate"))
  sim_add_block(lag, "integrator", "y")
  sim_add_block(lag, "outport", "out", index = 1)
  sim_connect(lag, "u", "k")
  sim_connect(lag, "k", "e", input = 1)
  sim_connect(lag, "y", "e", input = 2)
  sim_connect(lag, "e", "inv")
  sim_connect(lag, "inv", "y")
  sim_connect(lag, "y", "out")
  lag
}

test_that("subsystem instances match the flattened equivalent", {
  lag <- lag_subsystem()
  m <- sim_model("plant", params = list(r = 2))
  sim_add_block(m, "step", "u", time = 0.5)
  sim_add_block(m, "subsystem", "a", system = lag, params = list(rate = sim_param("r"), gain = 3))
  sim_connect(m, "u", "a")
  r <- tight(sim_compile(m), c(0, 3), times = seq(0, 3, 0.25))

  # hand-built equivalent
  h <- sim_model("flat")
  sim_add_block(h, "step", "u", time = 0.5)
  sim_add_block(h, "gain", "k", gain = 3)
  sim_add_block(h, "subtract", "e")
  sim_add_block(h, "gain", "inv", gain = 2)
  sim_add_block(h, "integrator", "y")
  sim_connect(h, "u", "k"); sim_connect(h, "k", "e", input = 1)
  sim_connect(h, "y", "e", input = 2); sim_connect(h, "e", "inv"); sim_connect(h, "inv", "y")
  rh <- tight(sim_compile(h), c(0, 3), times = seq(0, 3, 0.25))
  expect_equal(unname(sim_signal(r, "a")), unname(sim_signal(rh, "y")), tolerance = 1e-12)
  expect_equal(unname(sim_signal(r, "a/e")), unname(sim_signal(rh, "e")), tolerance = 1e-12)
  tt <- r$time
  expect_lt(max(abs(sim_signal(r, "a") - ifelse(tt < 0.5, 0, 3 * (1 - exp(-2 * (tt - 0.5)))))), 1e-8)
})

test_that("instances do not share state or parameters", {
  lag <- lag_subsystem()
  m <- sim_model()
  sim_add_block(m, "constant", "u", value = 1)
  sim_add_block(m, "subsystem", "fast", system = lag, params = list(rate = 10))
  sim_add_block(m, "subsystem", "slow", system = lag, params = list(rate = 1))
  sim_connect(m, "u", "fast")
  sim_connect(m, "u", "slow")
  r <- tight(sim_compile(m), c(0, 1), times = 1, initial = list(`slow/y` = 0.5))
  expect_equal(unname(sim_signal(r, "fast")), 1 - exp(-10), tolerance = 1e-8)
  expect_equal(unname(sim_signal(r, "slow")), 1 - 0.5 * exp(-1), tolerance = 1e-8)
  expect_equal(sort(colnames(sim_states(r))), c("fast/y", "slow/y"))
})

test_that("subsystems nest and resolve parameters through every level", {
  lag <- lag_subsystem()
  two <- sim_subsystem("two", params = list(rate = 4))
  sim_add_block(two, "inport", "in", index = 1)
  sim_add_block(two, "subsystem", "l1", system = lag)
  sim_add_block(two, "subsystem", "l2", system = lag)
  sim_add_block(two, "outport", "out", index = 1)
  sim_connect(two, "in", "l1"); sim_connect(two, "l1", "l2"); sim_connect(two, "l2", "out")
  m <- sim_model()
  sim_add_block(m, "constant", "u", value = 1)
  sim_add_block(m, "subsystem", "chain", system = two)
  sim_connect(m, "u", "chain")
  r <- tight(sim_compile(m), c(0, 2), times = 2)
  # two cascaded lags with rate 4: 1 - (1 + 4t) exp(-4t)
  expect_equal(unname(sim_signal(r, "chain")), 1 - (1 + 8) * exp(-8), tolerance = 1e-8)
  expect_true("chain/l1/y" %in% colnames(sim_states(r)))
})

test_that("subsystem errors name the offending path", {
  lag <- lag_subsystem()
  m <- sim_model()
  sim_add_block(m, "constant", "u")
  sim_add_block(m, "subsystem", "a", system = lag)
  sim_connect(m, "u", "a")
  expect_error(sim_compile(m), "Block 'a/inv'.*'rate'")
  bad <- sim_subsystem("bad")
  sim_add_block(bad, "inport", "i1", index = 2)
  m2 <- sim_model()
  expect_error(sim_add_block(m2, "subsystem", "s", system = bad), "without gaps")
})

test_that("a subsystem cannot contain itself", {
  s <- sim_subsystem("loopy")
  expect_error(sim_add_block(s, "subsystem", "me", system = s), "Subsystem cycle")
  outer <- sim_subsystem("outer")
  inner <- sim_subsystem("inner")
  sim_add_block(outer, "subsystem", "i", system = inner)
  expect_error(sim_add_block(inner, "subsystem", "o", system = outer), "Subsystem cycle")
  # a hierarchy changed behind the API is caught before it recurses
  bad <- sim_subsystem("bad")
  bad$blocks$self <- list(name = "self", type = "subsystem",
                          params = list(system = bad, params = list()))
  for (f in list(sim_compile, sim_copy, sim_model_to_list)) {
    expect_error(f(bad), "Subsystem cycle")
  }
})

test_that("declared port sizes seed size inference inside feedback", {
  half <- sim_subsystem("half")
  sim_add_block(half, "inport", "u", size = 3)
  sim_add_block(half, "gain", "g", gain = 0.5)
  sim_add_block(half, "outport", "y", size = 3)
  sim_connect(half, "u", "g")
  sim_connect(half, "g", "y")
  m <- sim_model()
  sim_add_block(m, "subsystem", "h", system = half)
  sim_connect(m, "h", "h")
  p <- sim_compile(m, algebraic_loops = "solve")
  expect_length(p$diagnostics$notes, 0)
  expect_equal(unname(sim_signal(sim_run(p, c(0, 1), times = 1), "h")), c(0, 0, 0))
})
