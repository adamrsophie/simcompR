test_that("results carry metadata, statistics and diagnostics", {
  r <- tight(sim_compile(decay_model(2)), c(0, 1))
  expect_s3_class(r, "sim_result")
  expect_equal(r$status, "success")
  expect_equal(r$metadata$params, list(a = 2))
  expect_equal(r$metadata$initial_continuous, c(x = 1))
  expect_false(is.na(r$metadata$deSolve))
  st <- sim_diagnostics(r)$stats
  expect_gt(st[["steps"]], 0)
  expect_equal(st[["segments"]], 1)
  expect_output(print(r), "status: success")
  expect_output(print(summary(r)), "Final continuous states")
  df <- as.data.frame(r)
  expect_equal(names(df)[1], "time")
  expect_equal(nrow(df), 201L)
  expect_error(sim_signal(r, "nope"), "Unknown signal")
})

test_that("solver failure is reported and never returned as success", {
  # dx/dt = x^2 from x0 = 1 blows up at t = 1
  m <- sim_model()
  sim_add_block(m, "integrator", "x", initial = 1)
  sim_add_block(m, "math", "sq", fun = "square")
  sim_connect(m, "x", "sq")
  sim_connect(m, "sq", "x")
  plan <- sim_compile(m)
  expect_error(sim_run(plan, c(0, 2)), "Simulation failed")
  expect_warning(r <- sim_run(plan, c(0, 2), on_failure = "warn"), "partial result")
  expect_equal(r$status, "failed")
  expect_false(r$success)
  expect_lt(max(r$time), 1)
  expect_false(anyNA(r$signals))
})

test_that("block errors during the run fail clearly", {
  m <- sim_model()
  sim_add_block(m, "time", "t")
  sim_add_block(m, "fcn", "f", fun = function(u, t) if (t > 1) stop("sensor offline") else u, size = 1)
  sim_add_block(m, "integrator", "x")
  sim_connect(m, "t", "f")
  sim_connect(m, "f", "x")
  expect_error(sim_run(sim_compile(m), c(0, 2)), "sensor offline")
})

test_that("plots draw without error", {
  withr::local_pdf(NULL)
  r <- sim_run(sim_compile(ball_model()), c(0, 1.5))
  expect_invisible(plot(r))
  expect_invisible(plot(r, c("h", "v")))
  m <- sim_model()
  sim_add_block(m, "sine", "u")
  sim_add_block(m, "zero_order_hold", "z", period = 0.3)
  sim_add_block(m, "scope", "sc")
  sim_connect(m, "u", "z"); sim_connect(m, "z", "sc")
  r2 <- sim_run(sim_compile(m), c(0, 3))
  expect_equal(r2$scopes, "sc")
  expect_equal(unname(sim_signal(r2, "sc")), unname(sim_signal(r2, "z")))
  expect_invisible(plot(r2))
  skip_if_not_installed("igraph")
  expect_invisible(plot(m))
})
